#!/usr/bin/env python3
"""Generate the bundled emoji key index and the emoji set's content hash.

Both the native app and the Wasm client embed the index, so EmojiAssets.has()
answers identically on each without the Wasm client carrying the images. The
hash versions the URLs the host serves the images from, so it changes only
when an image or the set does.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re
import sys

FILE_PATTERN = re.compile(r"<file>emoji/([0-9a-f]+(?:-[0-9a-f]+)*)\.svg</file>")


def _write_if_changed(path: Path, content: str) -> None:
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--qrc", type=Path, required=True)
    parser.add_argument("--index", type=Path, required=True)
    parser.add_argument("--header", type=Path, required=True)
    arguments = parser.parse_args()

    keys = sorted(FILE_PATTERN.findall(arguments.qrc.read_text(encoding="utf-8")))
    if not keys:
        print(f"emoji index error: no emoji/<key>.svg entries in {arguments.qrc}", file=sys.stderr)
        return 1
    set_hash = hashlib.sha256()
    for key in keys:
        image = arguments.qrc.parent / "emoji" / f"{key}.svg"
        set_hash.update(key.encode("ascii") + b"\0" + hashlib.sha256(image.read_bytes()).digest())

    _write_if_changed(arguments.index, "\n".join(keys) + "\n")
    _write_if_changed(arguments.header,
                      "#pragma once\n\n"
                      "// Generated by scripts/generate_emoji_index.py from resources/emoji.qrc.\n"
                      f'#define DECENZA_EMOJI_SET_HASH "{set_hash.hexdigest()}"\n')
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
