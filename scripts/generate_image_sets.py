#!/usr/bin/env python3
"""Generate the bundled emoji key index and the content hashes of the image sets the host serves.

Both the native app and the Wasm client embed the index, so EmojiAssets.has()
answers identically on each without the Wasm client carrying the images. Each
hash versions the URLs the host serves that set from, so it changes only when
an image in the set does.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re
import sys

EMOJI_PATTERN = re.compile(r"<file>emoji/([0-9a-f]+(?:-[0-9a-f]+)*)\.svg</file>")


def _write_if_changed(path: Path, content: str) -> None:
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _set_hash(files: list[Path]) -> str:
    digest = hashlib.sha256()
    for path in files:
        digest.update(path.name.encode("utf-8") + b"\0" + hashlib.sha256(path.read_bytes()).digest())
    return digest.hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--emoji-qrc", type=Path, required=True)
    parser.add_argument("--maps", type=Path, nargs="+", required=True)
    parser.add_argument("--index", type=Path, required=True)
    parser.add_argument("--header", type=Path, required=True)
    arguments = parser.parse_args()

    keys = sorted(EMOJI_PATTERN.findall(arguments.emoji_qrc.read_text(encoding="utf-8")))
    if not keys:
        print(f"image set error: no emoji/<key>.svg entries in {arguments.emoji_qrc}", file=sys.stderr)
        return 1
    emoji_dir = arguments.emoji_qrc.parent / "emoji"
    emoji_hash = _set_hash([emoji_dir / f"{key}.svg" for key in keys])
    map_hash = _set_hash(sorted(arguments.maps, key=lambda path: path.name))

    _write_if_changed(arguments.index, "\n".join(keys) + "\n")
    _write_if_changed(arguments.header,
                      "#pragma once\n\n"
                      "// Generated by scripts/generate_image_sets.py (cmake/image_sets.cmake).\n"
                      f'#define DECENZA_EMOJI_SET_HASH "{emoji_hash}"\n'
                      f'#define DECENZA_MAP_SET_HASH "{map_hash}"\n')
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
